def _ld(kind, title, desc, url, lang, base, site_title, date='', owner=''):
    typ = {'article': 'Article', 'about': 'AboutPage'}.get(kind, 'WebPage')
    d = {'@context': 'https://schema.org', '@type': typ, ('headline' if kind == 'article' else 'name'): title, 'description': desc,
         'inLanguage': lang, 'url': url, 'isPartOf': {'@type': 'WebSite', 'name': site_title, 'url': base + '/'}}
    if kind == 'article':
        d['mainEntityOfPage'] = url
    if DAY.match(date or ''):
        d['datePublished' if kind == 'article' else 'dateModified'] = date
    if owner:
        d['author'] = {'@type': 'Person', 'name': owner}
    return '<script type="application/ld+json">%s</script>' % json.dumps(d, ensure_ascii=False).replace('</', '<\\/')


def _page(it, body, base, site_title, rel, owner='', feeds=False):
    title = it['title']
    desc = it.get('summary') or re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', body)).strip()[:160]
    url = (base + '/' + _quote(rel)) if base else ''
    lang = 'en' if it.get('lang') == 'en' else 'zh-CN'
    head = ['<meta charset="utf-8">', '<meta name="viewport" content="width=device-width, initial-scale=1">',
            '<title>%s · %s</title>' % (esc(title, quote=False), esc(site_title, quote=False)),
            '<meta name="description" content="%s">' % esc(desc),
            '<meta name="robots" content="index, follow, max-image-preview:large">',
            '<meta property="og:type" content="article">', '<meta property="og:title" content="%s">' % esc(title),
            '<meta property="og:description" content="%s">' % esc(desc), '<meta property="og:site_name" content="%s">' % esc(site_title)]
    if owner:
        head.append('<meta name="author" content="%s">' % esc(owner))
    if DAY.match(it.get('date') or ''):
        head.append('<meta property="article:published_time" content="%s">' % it['date'])
    if url:
        head += ['<link rel="canonical" href="%s">' % esc(url), '<meta property="og:url" content="%s">' % esc(url),
                 _ld('article', title, desc, url, lang, base, site_title, it.get('date') or '', owner)]
    if feeds and base:
        head += _feed_links(base, site_title)
    head.append('<style>%s</style>' % CSS)
    meta = ' · '.join(x for x in (it.get('date') or '', it['category']) if x)
    read = '/#read/' + urllib.parse.quote(it['id'], safe='')
    return ('<!DOCTYPE html>\n<html lang="%s">\n<head>\n%s\n</head>\n<body>\n<article class="doc">\n<p class="meta">%s</p>\n<h1>%s</h1>\n%s\n'
            '<footer><a href="%s">在「%s」里阅读（带目录和阅读进度）</a> · <a href="/">返回首页</a><br>%s</footer>\n</article>\n</body>\n</html>\n'
            % (lang, '\n'.join(head), esc(meta, quote=False), esc(title, quote=False), body, esc(read), esc(site_title, quote=False), LEGAL_LINKS))


# ======================================================================= subscription feeds
FEED_LIMIT = 50


def _stamp(it):
    d = it.get('date') or ''
    return d + 'T00:00:00Z' if DAY.match(d) else None


def _kind(it):
    return 'tool' if it.get('project') else 'pdf' if it.get('type') == 'pdf' else 'note'


def _attr(s):
    return xml_escape(str(s), {'"': '&quot;'})


def _newest(items):
    return sorted(items, key=lambda i: (i.get('date') or '', i.get('added') or 0, i['id']), reverse=True)[:FEED_LIMIT]


def _feed_pair(rows, public, base, site_title, site_desc, owner, rel='feed', license=''):
    """(JSON Feed 1.1 text, Atom 1.0 text) of `rows`, published at <base>/<rel>.json and <base>/<rel>.xml. Summaries only: the feed brings readers to the page.

    JSON Feed wants content_text or content_html on every item, so the summary is also given as content_text.
    The `_shelf` keys are the small extension that lets other sites list this one (see SHELF-SPEC.md).
    """
    me = base + '/' + _quote(rel)
    latest = next((_stamp(i) for i in rows if _stamp(i)), '1970-01-01T00:00:00Z')
    zh = sum(1 for i in rows if i.get('lang') != 'en')
    lang = 'zh-CN' if zh >= len(rows) - zh else 'en'
    ext = {'spec': 1}
    if license:
        ext['license'] = license
    jf = {'version': 'https://jsonfeed.org/version/1.1', 'title': site_title, 'home_page_url': base + '/', 'feed_url': me + '.json',
          'language': lang, '_shelf': ext}
    if site_desc:
        jf['description'] = site_desc
    if owner:
        jf['authors'] = [{'name': owner}]
    jf['items'] = []
    for i in rows:
        url = base + '/' + _quote(public(i))
        tags = []
        for t in list(i.get('keywords') or []) + [i['category']]:
            if t and str(t) not in tags and len(tags) < 10:
                tags.append(str(t))
        item = {'id': url, 'url': url, 'title': i['title'], 'content_text': i.get('summary') or i['title']}
        if i.get('summary'):
            item['summary'] = i['summary']
        if _stamp(i):
            item['date_published'] = _stamp(i)
        shelf_ext = {'type': _kind(i), 'category': i['category']}
        if i.get('nodirectory'):                                 # stays on the site and in this feed, but a public directory is asked not to list it
            shelf_ext['listed'] = False
        item.update({'tags': tags, 'language': 'en' if i.get('lang') == 'en' else 'zh-CN', '_shelf': shelf_ext})
        jf['items'].append(item)
    author = owner or urllib.parse.urlsplit(base).netloc
    at = ['<?xml version="1.0" encoding="utf-8"?>', '<feed xmlns="http://www.w3.org/2005/Atom" xml:lang="%s">' % lang,
          '  <id>%s</id>' % xml_escape(base + '/' if rel == 'feed' else me + '.xml'), '  <title>%s</title>' % xml_escape(site_title)]   # the main feed keeps the id it always had
    if site_desc:
        at.append('  <subtitle>%s</subtitle>' % xml_escape(site_desc))
    at += ['  <link rel="self" type="application/atom+xml" href="%s.xml"/>' % _attr(me), '  <link rel="alternate" type="text/html" href="%s/"/>' % _attr(base),
           '  <updated>%s</updated>' % latest, '  <author><name>%s</name></author>' % xml_escape(author)]
    for i, item in zip(rows, jf['items']):
        at += ['  <entry>', '    <id>%s</id>' % xml_escape(item['id']), '    <title>%s</title>' % xml_escape(i['title']),
               '    <link rel="alternate" type="text/html" href="%s"/>' % _attr(item['url']),
               '    <updated>%s</updated>' % (_stamp(i) or latest)]
        if _stamp(i):
            at.append('    <published>%s</published>' % _stamp(i))
        if i.get('summary'):
            at.append('    <summary type="text">%s</summary>' % xml_escape(i['summary']))
        at += ['    <category term="%s"/>' % _attr(t) for t in item['tags']]
        at.append('  </entry>')
    at.append('</feed>')
    return json.dumps(jf, ensure_ascii=False, indent=2) + '\n', '\n'.join(at) + '\n'


def build_feeds(items, public, base, site_title, site_desc, owner, license=''):
    """The main feed: (JSON Feed text, Atom text) of the newest FEED_LIMIT items."""
    return _feed_pair(_newest(items), public, base, site_title, site_desc, owner, 'feed', license)


