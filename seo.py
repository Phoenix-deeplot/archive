def site_url(cli=''):
    """Public address of the site without a trailing slash, '' when unknown.

    --site-url, then $SITE_URL, then on Vercel the project's production domain (a custom domain if there is one).
    """
    url = (cli or os.environ.get('SITE_URL') or os.environ.get('VERCEL_PROJECT_PRODUCTION_URL') or '').strip()
    if url and not re.match(r'https?://', url):
        url = 'https://' + url
    return url.rstrip('/')


# ======================================================================= Markdown -> HTML
_PLACE = re.compile('\x00(\\d+)\x00')


_RESOLVE = None      # set by md_to_html(): library path -> public path (articles are published under cleaned-up addresses)


def _safe_url(url, base_dir, image=False):
    """A URL that is safe to put in href / src, or None. Relative ones are resolved inside library/."""
    url = url.strip().replace('\x00', '')
    if not url:
        return None
    if url.startswith('#'):
        return url
    parts = urllib.parse.urlsplit(url)
    if parts.scheme:
        return url if parts.scheme.lower() in (('http', 'https') if image else ('http', 'https', 'mailto')) else None
    if url.startswith('//'):
        return None
    if url.startswith('/'):
        return url
    # relative links are often percent-encoded ("My%20Note.md", Chinese names): decode first, or they would be encoded twice
    joined = posixpath.normpath(posixpath.join(base_dir, urllib.parse.unquote(parts.path))) if parts.path else base_dir
    if joined.startswith('..') or joined.startswith('/'):
        return None                                   # would leave library/
    out = '/' + urllib.parse.quote(_RESOLVE(joined)) if _RESOLVE else '/library/' + urllib.parse.quote(joined)
    if parts.query:
        out += '?' + parts.query
    if parts.fragment:
        out += '#' + parts.fragment
    return out


def _inline(text, base_dir, stash=None):
    top = stash is None
    stash = [] if top else stash

    def keep(h):
        stash.append(h)
        return '\x00%d\x00' % (len(stash) - 1)

    text = text.replace('\x00', '')
    text = re.sub(r'\\([\\`*_{}\[\]()#+\-.!|~<>])', lambda m: keep(esc(m.group(1), quote=False)), text)
    text = re.sub(r'(`+)(.+?)\1', lambda m: keep('<code>%s</code>' % esc(m.group(2).strip(), quote=False)), text)

    def image(m):
        src = _safe_url(m.group(2), base_dir, image=True)
        return keep('<img src="%s" alt="%s">' % (esc(src), esc(m.group(1)))) if src else esc(m.group(1), quote=False)

    text = re.sub(r'!\[([^\]]*)\]\(\s*([^)\s]+)(?:\s+"[^"]*")?\s*\)', image, text)

    def link(m):
        href = _safe_url(m.group(2), base_dir)
        inner = _inline(m.group(1), base_dir, stash)
        return keep('<a href="%s">%s</a>' % (esc(href), inner)) if href else inner

    text = re.sub(r'\[([^\]]+)\]\(\s*([^)\s]+)(?:\s+"[^"]*")?\s*\)', link, text)
    text = re.sub(r'<(https?://[^\s<>]+)>', lambda m: keep('<a href="%s">%s</a>' % (esc(m.group(1)), esc(m.group(1), quote=False))), text)
    text = esc(text, quote=False)
    text = re.sub(r'\*\*(?=\S)(.+?)(?<=\S)\*\*', r'<strong>\1</strong>', text)
    text = re.sub(r'(?<!\w)__(?=\S)(.+?)(?<=\S)__(?!\w)', r'<strong>\1</strong>', text)
    text = re.sub(r'\*(?=\S)(.+?)(?<=\S)\*', r'<em>\1</em>', text)
    text = re.sub(r'(?<!\w)_(?=\S)(.+?)(?<=\S)_(?!\w)', r'<em>\1</em>', text)
    text = re.sub(r'~~(?=\S)(.+?)(?<=\S)~~', r'<del>\1</del>', text)
    text = re.sub(r' {2,}\n', '<br>\n', text)
    if top:
        while _PLACE.search(text):
            text = _PLACE.sub(lambda m: stash[int(m.group(1))], text)
    return text


_FENCE = re.compile(r'^\s{0,3}(`{3,}|~{3,})\s*([\w+#.-]*)')
_HEADING = re.compile(r'^\s{0,3}(#{1,6})\s+(.*?)\s*#*\s*$')
_HR = re.compile(r'^\s{0,3}([-*_])(?:\s*\1){2,}\s*$')
_LIST = re.compile(r'^(\s*)([-*+]|\d{1,9}[.)])\s+(.*)$')
_QUOTE = re.compile(r'^\s{0,3}>')
_SETEXT = re.compile(r'^\s{0,3}(=+|-+)\s*$')
_TABLE_SEP = re.compile(r'^\s*\|?\s*:?-+:?\s*(?:\|\s*:?-+:?\s*)*\|?\s*$')


def _cells(line):
    line = line.strip()
    if line.startswith('|'):
        line = line[1:]
    if line.endswith('|') and not line.endswith('\\|'):
        line = line[:-1]
    return [c.strip().replace('\\|', '|') for c in re.split(r'(?<!\\)\|', line)]


def _is_table(line, nxt):
    return '|' in line and '|' in nxt and _TABLE_SEP.match(nxt) is not None and len(_cells(line)) == len(_cells(nxt))


def _starts_block(line, nxt=''):
    return bool(_HEADING.match(line) or _HR.match(line) or _FENCE.match(line) or _QUOTE.match(line)
                or _LIST.match(line) or _is_table(line, nxt))


def _list(lines, i, base_dir):
    n = len(lines)
    m = _LIST.match(lines[i].expandtabs(4))
    base = len(m.group(1))
    ordered = m.group(2)[0].isdigit()
    start = int(m.group(2)[:-1]) if ordered else 1
    items, cur = [], None
    while i < n:
        line = lines[i].expandtabs(4)
        if not line.strip():                      # a blank line belongs to the list only if more of it follows
            j = i + 1
            while j < n and not lines[j].strip():
                j += 1
            if j < n:
                nxt = lines[j].expandtabs(4)
                ind = len(nxt) - len(nxt.lstrip())
                mm = _LIST.match(nxt)
                if ind > base or (mm and ind == base and mm.group(2)[0].isdigit() == ordered):
                    if cur is not None:
                        cur.append('')
                    i += 1
                    continue
            break
        mm = _LIST.match(line)
        ind = len(line) - len(line.lstrip())
        if mm and ind == base and mm.group(2)[0].isdigit() == ordered:
            cur = [mm.group(3)]
            items.append(cur)
        elif ind > base and cur is not None:     # nested content: take it out one level
            cur.append(line[min(ind, base + 2):])
        elif not mm and cur is not None and not _starts_block(line):
            cur.append(line.strip())             # lazy continuation of the item's text
        else:
            break
        i += 1
    lis = []
    for body in items:
        box = ''
        mt = re.match(r'^\[( |x|X)\]\s+', body[0])
        if mt:
            box = '☑ ' if mt.group(1) in 'xX' else '☐ '
            body[0] = body[0][mt.end():]
        inner = _blocks(body, base_dir)
        if '' not in body:                         # tight item (no blank lines): its first paragraph is plain text
            inner = re.sub(r'^<p>((?:(?!</p>).)*)</p>', r'\1', inner, count=1, flags=re.S)
        lis.append('<li>%s%s</li>' % (box, inner))
    tag = 'ol' if ordered else 'ul'
    open_tag = '<ol start="%d">' % start if ordered and start != 1 else '<%s>' % tag
    return '%s\n%s\n</%s>' % (open_tag, '\n'.join(lis), tag), i


def _blocks(lines, base_dir):
    out, i, n = [], 0, len(lines)
    while i < n:
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        m = _FENCE.match(line)
        if m:
            fence, lang, body = m.group(1), m.group(2), []
            closing = re.compile(r'^\s{0,3}%s{%d,}\s*$' % (re.escape(fence[0]), len(fence)))
            i += 1
            while i < n and not closing.match(lines[i]):
                body.append(lines[i])
                i += 1
            i += 1
            out.append('<pre><code%s>%s</code></pre>' % (' class="language-%s"' % esc(lang) if lang else '', esc('\n'.join(body), quote=False)))
            continue
        m = _HEADING.match(line)
        if m:
            level = len(m.group(1))
            out.append('<h%d>%s</h%d>' % (level, _inline(m.group(2), base_dir), level))
            i += 1
            continue
        if _HR.match(line):
            out.append('<hr>')
            i += 1
            continue
        if _QUOTE.match(line):
            quoted = []
            while i < n and _QUOTE.match(lines[i]):
                quoted.append(re.sub(r'^\s{0,3}> ?', '', lines[i]))
                i += 1
            out.append('<blockquote>\n%s\n</blockquote>' % _blocks(quoted, base_dir))
            continue
        nxt = lines[i + 1] if i + 1 < n else ''
        if _is_table(line, nxt):
            head = _cells(line)
            aligns = []
            for c in _cells(nxt):
                aligns.append(' style="text-align:center"' if c.startswith(':') and c.endswith(':') else
                              ' style="text-align:right"' if c.endswith(':') else '')
            i += 2
            rows = []
            while i < n and lines[i].strip() and '|' in lines[i]:
                cells = _cells(lines[i])[:len(head)]
                rows.append(cells + [''] * (len(head) - len(cells)))
                i += 1
            th = ''.join('<th%s>%s</th>' % (aligns[k], _inline(c, base_dir)) for k, c in enumerate(head))
            tr = ''.join('<tr>%s</tr>\n' % ''.join('<td%s>%s</td>' % (aligns[k], _inline(c, base_dir)) for k, c in enumerate(r)) for r in rows)
            out.append('<table>\n<thead><tr>%s</tr></thead>\n<tbody>\n%s</tbody>\n</table>' % (th, tr))
            continue
        if _LIST.match(line):
            html, i = _list(lines, i, base_dir)
            out.append(html)
            continue
        para = [line.lstrip()]
        i += 1
        heading = 0
        while i < n and lines[i].strip():
            s = _SETEXT.match(lines[i])
            if s:
                heading = 1 if s.group(1)[0] == '=' else 2
                i += 1
                break
            if _starts_block(lines[i], lines[i + 1] if i + 1 < n else ''):
                break
            para.append(lines[i].lstrip())
            i += 1
        if heading:
            out.append('<h%d>%s</h%d>' % (heading, _inline(' '.join(p.strip() for p in para), base_dir), heading))
        else:
            out.append('<p>%s</p>' % _inline('\n'.join(para).strip(), base_dir))
    return '\n'.join(out)


def md_to_html(md, base_dir='', resolve=None):
    """Markdown -> safe HTML. base_dir: folder of the file inside library/; resolve: maps a library path to its public path."""
    global _RESOLVE
    _RESOLVE = resolve
    try:
        return _blocks(md.replace('\r\n', '\n').replace('\r', '\n').split('\n'), base_dir)
    finally:
        _RESOLVE = None


def txt_to_html(text):
    paras = [p for p in re.split(r'\n\s*\n', text.replace('\r\n', '\n').replace('\r', '\n').strip()) if p.strip()]
    return '\n'.join('<p>%s</p>' % '<br>\n'.join(esc(l.strip(), quote=False) for l in p.split('\n')) for p in paras)


