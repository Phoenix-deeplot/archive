"""
seo.py — the site that gets deployed, built by `build_index.py --seo` into dist/. Your own files are never changed.

dist/ is a copy of the site in which
* library/**/*.html          get the search-engine tags they lack (description, canonical, Open Graph, JSON-LD, lang)
* articles/<category>/<name>.html   a page with the FULL TEXT of every Markdown / TXT article (they have no page of
                                    their own; HTML and PDF files are pages already)
* sitemap.xml, robots.txt    need the public address of the site (see build_index.py --site-url)
* index.html                 gets canonical + JSON-LD and a plain list of every article for crawlers without JavaScript
* manifest.json / manifest.js   carry the article page of each Markdown / TXT item, so cards link to real pages

Hidden items are not copied at all (they are not published), and library/_meta.json is left out. noindex items are
published but get no sitemap entry. Only the standard library is used. Markdown is converted here and everything
that is not a tag built by this file is HTML-escaped, so an article cannot inject markup.
"""
