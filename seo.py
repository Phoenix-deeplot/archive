def build_feed_groups(items, public, base, site_title, site_desc, owner, license=''):
    """One feed per category (feed/books.xml) and per tag (feed/tag/<tag>.xml), as {path: text}, and feed/index.json that lists them.

    The page reads feed/index.json to offer "subscribe to what you are looking at". Tags are the items' `keywords`.
    """
    cats, tags = {}, {}
    for it in items:
        cats.setdefault(it['category'], []).append(it)
        for t in dict.fromkeys(str(k).strip() for k in (it.get('keywords') or []) if str(k).strip()):
            tags.setdefault(t.casefold(), (t, []))[1].append(it)
    out, index, used = {}, {'spec': 1, 'categories': [], 'tags': []}, set()

    def one(rel, title, rows, entry):
        j, a = _feed_pair(_newest(rows), public, base, title, site_desc, owner, rel, license)
        out[rel + '.json'], out[rel + '.xml'] = j, a
        index[entry['kind']].append({**entry['row'], 'n': len(rows), 'atom': _quote(rel) + '.xml', 'json': _quote(rel) + '.json'})

    def free(rel):                                              # two names may slugify to the same address
        cand, n = rel, 1
        while cand in used:
            n += 1
            cand = '%s-%d' % (rel, n)
        used.add(cand)
        return cand

    for key in sorted(cats):
        name = CATEGORY_LABEL.get(key, key)
        one(free('feed/' + slugify(key)), '%s · %s' % (site_title, name), cats[key], {'kind': 'categories', 'row': {'key': key, 'name': name}})
    for _, (name, rows) in sorted(tags.items(), key=lambda kv: (-len(kv[1][1]), kv[0]))[:MAX_TAG_FEEDS]:
        one(free('feed/tag/' + slugify(name)), '%s · #%s' % (site_title, name), rows, {'kind': 'tags', 'row': {'name': name}})
    out['feed/index.json'] = json.dumps(index, ensure_ascii=False, indent=1) + '\n'
    return out


def _feed_links(base, site_title):
    """Autodiscovery: feed readers find the feeds from the page address alone."""
    return ['<link rel="alternate" type="application/atom+xml" title="%s" href="%s/feed.xml">' % (_attr(site_title), _attr(base)),
            '<link rel="alternate" type="application/feed+json" title="%s" href="%s/feed.json">' % (_attr(site_title), _attr(base))]


def _read_text(library, item_id):
    with open(os.path.join(library, *item_id.split('/')), 'r', encoding='utf-8-sig', errors='replace') as f:
        return f.read()


def _article_body(it, library, front_matter, resolve=None):
    raw = _read_text(library, it['id'])
    if it['type'] == 'txt':
        lines = raw.strip().split('\n', 1)                       # the first line is the title, as on the card
        return txt_to_html(lines[1] if len(lines) > 1 else '')
    body = front_matter(raw)[1]
    html = md_to_html(body, posixpath.dirname(it['id']), resolve)
    return re.sub(r'^\s*<h1>.*?</h1>\n?', '', html, count=1, flags=re.S)   # the page has its own <h1>


# ======================================================================= public addresses
def slugify(s):
    """A short, readable, lower-case address part: letters, digits and CJK stay; spaces, punctuation and '_' become '-'."""
    s = re.sub(r'[^\w]+', '-', s.strip()).replace('_', '-')
    s = re.sub(r'-{2,}', '-', s).strip('-').lower()
    return s[:60].rstrip('-') or 'page'


def _seg(s):
    return s if re.fullmatch(r'[\w.\-]+', s) else slugify(s)


def map_dir(d):
    return '/'.join(_seg(s) for s in d.split('/') if s)


def plan(items):
    """Public address of every published item, relative to the site root (no leading slash).

    library/books/重资产 读书笔记.html -> books/重资产-读书笔记.html ; library/tools/My App/index.html -> tools/my-app/ ;
    `slug` in _meta.json / <meta name="archive:slug"> / front matter overrides the name. Two items never share an address.
    Returns (file_map {id: path}, proj_map {old folder: new folder}, page_map {id: articles/....html}).
    """
    used, used_pages = set(), set()
    file_map, proj_map, page_map = {}, {}, {}

    def unique(path, pool):
        stem, ext = posixpath.splitext(path)
        p, n = path, 2
        while p.lower() in pool:
            p = '%s-%d%s' % (stem, n, ext)
            n += 1
        pool.add(p.lower())
        return p

    for it in sorted(items, key=lambda i: i['id']):
        parent = posixpath.dirname(it['id'])
        if it.get('project'):
            gp = posixpath.dirname(parent)
            new_dir = unique('/'.join(x for x in (map_dir(gp), slugify(it.get('slug') or posixpath.basename(parent))) if x), used)
            proj_map[parent] = new_dir
            continue
        stem, ext = posixpath.splitext(posixpath.basename(it['id']))
        file_map[it['id']] = unique('/'.join(x for x in (map_dir(parent), slugify(it.get('slug') or stem) + ext.lower()) if x), used)
        if it.get('type') in ('md', 'txt'):
            page_map[it['id']] = unique(ARTICLES + '/' + posixpath.splitext(file_map[it['id']])[0] + '.html', used_pages)
    return file_map, proj_map, page_map


def new_path(it, file_map, proj_map):
    if it.get('project'):
        return proj_map[posixpath.dirname(it['id'])] + '/' + posixpath.basename(it['id'])
    return file_map[it['id']]


def url_path(it, file_map, proj_map):
    """The address to publish: a tool is its folder (the trailing slash keeps its relative css / js working)."""
    return proj_map[posixpath.dirname(it['id'])] + '/' if it.get('project') else file_map[it['id']]


def _read(path):
    with open(path, 'r', encoding='utf-8', errors='replace', newline='') as f:
        return f.read()


def _write_if_changed(path, text):
    try:
        with open(path, 'r', encoding='utf-8', newline='') as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(text)
    return True


def _inject(text, name, content):
    pat = re.compile(r'(<!-- seo:%s -->)(.*?)(<!-- /seo:%s -->)' % (name, name), re.S)
    return pat.sub(lambda m: m.group(1) + '\n' + (content + '\n' if content else '') + m.group(3), text, count=1)


def _meta_of(text, name):
    m = re.search(r'<meta\s+name="%s"\s+content="([^"]*)"' % name, text)
    return m.group(1) if m else ''


def load_site_config(root):
    """site.json (optional, never published): {"owner": "...", "contact": "you@example.com"}."""
    try:
        with open(os.path.join(root, 'site.json'), 'r', encoding='utf-8-sig') as f:
            d = json.load(f)
        return d if isinstance(d, dict) else {}
    except (OSError, ValueError):
        return {}


def _fill_site(text, cfg):
    """<span data-site="owner">default</span> / <span data-site="contact">default</span> become what site.json says."""
    def fill(key, render):
        nonlocal text
        val = str(cfg.get(key) or '').strip()
        if val:
            text = re.sub(r'<span data-site="%s">.*?</span>' % key, lambda m: render(val), text, flags=re.S)
    fill('owner', lambda v: esc(v, quote=False))
    fill('contact', lambda v: '<a href="mailto:%s">%s</a>' % (esc(v), esc(v, quote=False)) if re.fullmatch(r'[^@\s]+@[^@\s]+\.[^@\s]+', v) else esc(v, quote=False))
    return text


# ======================================================================= the published copy
SKIP_ROOT_FILES = {'serve.py', 'build_index.py', 'seo.py', 'README.md', 'vercel.json', 'manifest.json', 'manifest.js', 'site.json'}
SKIP_DIRS = {'__pycache__', 'node_modules'}


def _meta_has(head, pattern):
    return re.search(pattern, head, re.I) is not None


def patch_page(text, it, base, site_title, path, kind='article', owner=''):
    """Add the search-engine tags a page lacks (never changes or duplicates what it already has).

    `path` is the page's public address (no leading slash). Returns (new text, problems worth telling the owner about).
    """
    end = re.search(r'</head\s*>', text, re.I)
    if not end:
        return text, ['no </head>, left as it is']
    start = re.search(r'<head\b[^>]*>', text, re.I)
    head = text[start.end():end.start()] if start and start.end() <= end.start() else text[:end.start()]
    title, desc = it['title'], it.get('summary') or ''
    url = base + '/' + _quote(path) if base else ''
    lang = 'en' if it.get('lang') == 'en' else 'zh-CN'
    add, problems = [], []
    if not _meta_has(head, r'<title[^>]*>\s*\S'):
        add.append('<title>%s</title>' % esc(title, quote=False))
    if desc and not _meta_has(head, r'<meta[^>]+name=["\']description["\']'):
        add.append('<meta name="description" content="%s">' % esc(desc))
    if url and not _meta_has(head, r'<link[^>]+rel=["\']canonical["\']'):
        add.append('<link rel="canonical" href="%s">' % esc(url))
    for prop, val in (('og:type', 'article' if kind == 'article' else 'website'), ('og:title', title), ('og:description', desc), ('og:url', url),
                      ('og:site_name', site_title), ('og:locale', 'en_US' if lang == 'en' else 'zh_CN')):
        if val and not _meta_has(head, r'<meta[^>]+property=["\']%s["\']' % re.escape(prop)):
            add.append('<meta property="%s" content="%s">' % (prop, esc(val)))
    if kind == 'article' and DAY.match(it.get('date') or '') and not _meta_has(head, r'article:published_time'):
        add.append('<meta property="article:published_time" content="%s">' % it['date'])
    if owner and not _meta_has(head, r'<meta[^>]+name=["\']author["\']'):
        add.append('<meta name="author" content="%s">' % esc(owner))
    if not _meta_has(head, r'<meta[^>]+name=["\']twitter:card["\']'):
        add.append('<meta name="twitter:card" content="summary">')
    if url and not _meta_has(head, r'application/ld\+json'):
        add.append(_ld(kind, title, desc, url, lang, base, site_title, it.get('date') or '', owner))
    if not _meta_has(head, r'<meta[^>]+name=["\']viewport["\']'):
        problems.append('no <meta name="viewport"> (Google ranks pages that are not mobile friendly lower)')
    if add:
        block = '<!-- seo:page -->\n' + '\n'.join(add) + '\n<!-- /seo:page -->\n'
        text = text[:end.start()] + block + text[end.start():]
    m = re.search(r'<html\b([^>]*)>', text, re.I)
    if m and not re.search(r'\blang\s*=', m.group(1), re.I):
        text = text[:m.start()] + '<html lang="%s"%s>' % (lang, m.group(1)) + text[m.end():]
    return text, problems


def _root_names(root, library, out_name):
    names = []
    for name in sorted(os.listdir(root)):
        if name.startswith('.') or name in SKIP_DIRS or name in (out_name, ARTICLES, os.path.basename(library)):
            continue
        if os.path.isfile(os.path.join(root, name)) and name in SKIP_ROOT_FILES:
            continue
        names.append(name)
    return names


def _copy_site(root, library, out, out_name, hidden_files, hidden_dirs, file_map, proj_map):
    def dest_rel(relfile):
        if relfile in file_map:
            return file_map[relfile]
        for old, new in proj_map.items():
            if relfile.startswith(old + '/'):
                return new + relfile[len(old):]
        d, f = posixpath.split(relfile)
        return (map_dir(d) + '/' + f) if d else f

    for name in _root_names(root, library, out_name):
        src = os.path.join(root, name)
        if os.path.isfile(src):
            shutil.copy2(src, os.path.join(out, name))
        else:
            shutil.copytree(src, os.path.join(out, name), ignore=shutil.ignore_patterns('.*', '__pycache__', 'node_modules'))
    for d, dns, fns in os.walk(library):
        rel = os.path.relpath(d, library).replace(os.sep, '/')
        dns[:] = [x for x in dns if not x.startswith('.') and x not in SKIP_DIRS and (x if rel == '.' else rel + '/' + x) not in hidden_dirs]
        for f in fns:
            relfile = f if rel == '.' else rel + '/' + f
            if f.startswith('.') or relfile in hidden_files or (rel == '.' and f == '_meta.json'):
                continue
            dst = os.path.join(out, *dest_rel(relfile).split('/'))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(os.path.join(d, f), dst)
    return dest_rel


def publish(items, base, root, library, front_matter, write_manifest, out_name='dist'):
    """Build the site that gets deployed into <root>/<out_name>/ and leave every source file alone.

    The copy has no hidden items and no library/_meta.json; items sit at short addresses (no library/ in front, readable
    names); every HTML page gets the search-engine tags it lacks; every Markdown / TXT article gets a full-text page;
    about / privacy / terms are filled from site.json; sitemap.xml and robots.txt are written. Returns counts for the log.
    """
    # one plain folder name directly under the project: never a path (it would end up inside the tree it copies), never a real folder of the site
    if not re.fullmatch(r'\w[\w.-]*', out_name) or out_name in (os.path.basename(library), 'vendor', ARTICLES):
        raise SystemExit('refusing to use %r as the output folder: give a plain folder name such as dist' % out_name)
    out = os.path.join(root, out_name)
    if os.path.isdir(out) and os.listdir(out) and not os.path.exists(os.path.join(out, MARKER)):
        raise SystemExit('%s/ already exists and was not made by this script; remove it or choose another folder' % out_name)

    listed, skipped = [], {'hidden': 0, 'noindex': 0}
    hidden_files, hidden_dirs = set(), set()
    for it in items:
        if it.get('hidden'):
            skipped['hidden'] += 1
            if it.get('project'):
                hidden_dirs.add(posixpath.dirname(it['id']))
            else:
                hidden_files.add(it['id'])
        elif it.get('noindex'):
            skipped['noindex'] += 1
        else:
            listed.append(it)
    visible = [it for it in items if not it.get('hidden')]          # what is published at all (noindex ones too)

    file_map, proj_map, page_map = plan(visible)
    reserved = {n.lower() for n in _root_names(root, library, out_name)} | {ARTICLES, MARKER.lower(), 'sitemap.xml', 'robots.txt', 'manifest.json', 'manifest.js', 'index.html', 'feed', 'feed.xml', 'feed.json'}
    clash = sorted({p.split('/')[0] for p in list(file_map.values()) + list(proj_map.values()) if p.split('/')[0].lower() in reserved})
    if clash:
        raise SystemExit('these names in library/ would collide with files of the site itself: %s. Rename them.' % ', '.join(clash))

    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)
    _write_if_changed(os.path.join(out, MARKER), 'Written by build_index.py --seo; emptied and rewritten on every run.\n')
    cfg = load_site_config(root)
    owner = str(cfg.get('owner') or '').strip()
    # feeds are written only with a site address, and never over a feed.xml / feed.json the owner put in the project root
    make_feeds = bool(base) and not any(os.path.exists(os.path.join(root, n)) for n in ('feed.xml', 'feed.json'))
    dest_rel = _copy_site(root, library, out, out_name, hidden_files, hidden_dirs, file_map, proj_map)

    def resolve(joined):                                             # a library path -> where it is published
        return page_map.get(joined) or dest_rel(joined)

    index_path = os.path.join(out, 'index.html')
    index = _read(index_path) if os.path.exists(index_path) else ''
    m = re.search(r'<title>(.*?)</title>', index, re.S)
    site_title, site_desc = (m.group(1).strip() if m else 'My Archive'), _meta_of(index, 'description')

    # --- a page with the full text for every Markdown / TXT article
    pages = {}
    for it in [x for x in listed if x.get('type') in ('md', 'txt')]:
        try:
            rel = page_map[it['id']]
            _write_if_changed(os.path.join(out, *rel.split('/')), _page(it, _article_body(it, library, front_matter, resolve), base, site_title, rel, owner, make_feeds))
            pages[it['id']] = rel
        except OSError:
            continue

    def public(it):
        return pages.get(it['id']) or url_path(it, file_map, proj_map)

    # --- the missing tags on every HTML page (only in the copy)
    patched, problems = 0, {}
    for it in visible:
        if it.get('type') != 'html':
            continue
        target = os.path.join(out, *new_path(it, file_map, proj_map).split('/'))
        try:
            with open(target, 'rb') as f:
                raw = f.read()
            bom = raw.startswith(b'\xef\xbb\xbf')
            text = raw[3:].decode('utf-8') if bom else raw.decode('utf-8')
        except (OSError, UnicodeDecodeError):
            problems.setdefault('not UTF-8, tags not added', []).append(it['id'])
            continue
        new, probs = patch_page(text, it, base, site_title, url_path(it, file_map, proj_map), 'article', owner)
        for p in probs:
            problems.setdefault(p, []).append(it['id'])
        if new != text:
            with open(target, 'wb') as f:
                f.write((b'\xef\xbb\xbf' if bom else b'') + new.encode('utf-8'))
            patched += 1

    # --- about / privacy / terms: fill owner + contact from site.json, add the tags
    legal = []
    for name in LEGAL_PAGES:
        target = os.path.join(out, name)
        if not os.path.exists(target):
            continue
        text = _fill_site(_read(target), cfg)
        t = re.search(r'<title>(.*?)</title>', text, re.S)
        d = re.search(r'最后更新[：:]\s*(\d{4}-\d{2}-\d{2})', text)
        pseudo = {'title': (t.group(1).strip() if t else name), 'summary': _meta_of(text, 'description'), 'date': d.group(1) if d else '', 'lang': 'zh'}
        text, probs = patch_page(text, pseudo, base, site_title, name, LEGAL_KIND[name], owner)
        _write_if_changed(target, text)
        legal.append((name, pseudo['date']))

    # --- manifest of the published site: no hidden items, public paths, article pages
    published = []
    for it in visible:
        d = dict(it)
        d['path'] = new_path(it, file_map, proj_map)
        if it['id'] in pages:
            d['page'] = pages[it['id']]
        published.append(d)
    write_manifest(published, out)

    # --- sitemap.xml + robots.txt (a hand-written one at the project root is kept as it is)
    notice = ''
    entries = [it for it in listed if it.get('type') in ('html', 'pdf') or it['id'] in pages]
    if base:
        dates = [i['date'] for i in entries if DAY.match(i.get('date') or '')]
        rows = [(base + '/', max(dates) if dates else '')] + [(base + '/' + _quote(public(i)), i.get('date') or '') for i in entries]
        rows += [(base + '/' + n, d) for n, d in legal]
        xml = ['<?xml version="1.0" encoding="UTF-8"?>', '<!-- %s -->' % GENERATED, '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
        for loc, d in rows:
            xml.append('  <url><loc>%s</loc>%s</url>' % (xml_escape(loc), '<lastmod>%s</lastmod>' % d if DAY.match(d) else ''))
        xml.append('</urlset>')
        robots = ['# ' + GENERATED, 'User-agent: *', 'Allow: /', 'Disallow: /manifest.json', 'Disallow: /manifest.js']
        robots += ['Disallow: /' + _quote(new_path(i, file_map, proj_map)) for i in visible if i.get('noindex')]
        robots += ['', 'Sitemap: ' + base + '/sitemap.xml']
        for name, text in (('sitemap.xml', '\n'.join(xml) + '\n'), ('robots.txt', '\n'.join(robots) + '\n')):
            src = os.path.join(root, name)
            if os.path.exists(src) and GENERATED not in _read(src):
                notice += ('; ' if notice else '') + '%s at the project root is yours, so it is published as it is' % name
            else:
                _write_if_changed(os.path.join(out, name), text)
    if base and not make_feeds:
        notice += ('; ' if notice else '') + 'feed.xml / feed.json at the project root are yours, so no feed was generated'
    if make_feeds:
        lic = str(cfg.get('license') or '').strip()
        feed_json, feed_atom = build_feeds(listed, public, base, site_title, site_desc, owner, lic)
        _write_if_changed(os.path.join(out, 'feed.json'), feed_json)
        _write_if_changed(os.path.join(out, 'feed.xml'), feed_atom)
        for rel, text in build_feed_groups(listed, public, base, site_title, site_desc, owner, lic).items():
            _write_if_changed(os.path.join(out, *rel.split('/')), text)

    # --- index.html of the published site
    if index:
        head = []
        if base:
            head += ['<link rel="canonical" href="%s/">' % esc(base), '<meta property="og:url" content="%s/">' % esc(base)]
        if make_feeds:
            head += _feed_links(base, site_title)
        if owner:
            head.append('<meta name="author" content="%s">' % esc(owner))
        for env, name in (('GOOGLE_SITE_VERIFICATION', 'google-site-verification'), ('BING_SITE_VERIFICATION', 'msvalidate.01')):
            if os.environ.get(env, '').strip():
                head.append('<meta name="%s" content="%s">' % (name, esc(os.environ[env].strip())))
        if base:
            listing = [{'@type': 'ListItem', 'position': n, 'url': base + '/' + _quote(public(i)), 'name': i['title']} for n, i in enumerate(entries[:100], 1)]
            site = {'@type': 'WebSite', 'name': site_title, 'url': base + '/', 'description': site_desc}
            if owner:
                site['publisher'] = {'@type': 'Person', 'name': owner}
            head.append('<script type="application/ld+json">%s</script>' % json.dumps({'@context': 'https://schema.org', '@graph': [site, {'@type': 'ItemList', 'itemListElement': listing}]}, ensure_ascii=False).replace('</', '<\\/'))
        body = ['<noscript>', '<h1>%s</h1>' % esc(site_title, quote=False), '<p>%s</p>' % esc(site_desc, quote=False), '<ul>']
        for it in listed:
            body.append('<li><a href="%s">%s</a>%s</li>' % (esc(_quote(public(it))), esc(it['title'], quote=False),
                                                           ' — ' + esc(it['summary'], quote=False) if it.get('summary') else ''))
        body += ['</ul>', '<p>%s</p>' % LEGAL_LINKS.replace('href="/', 'href="'), '</noscript>']
        _write_if_changed(index_path, _inject(_inject(index, 'head', '\n'.join(head)), 'body', '\n'.join(body)))

    return {'urls': len(entries) + 1 + len(legal) if base else 0, 'pages': len(pages), 'patched': patched, 'skipped': skipped,
            'problems': problems, 'notice': notice, 'out': out_name, 'legal': len(legal), 'feeds': make_feeds, 'owner': bool(owner), 'contact': bool(str(cfg.get('contact') or '').strip())}
